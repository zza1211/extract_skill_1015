// 新架构工具桥接回归：主agent自主提交和标签学习，独立票不产生学习来源。
// 使用合成上下文验证协议；真实会话来源另由CLI运输测试检查。
import assert from "node:assert/strict";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {mkdtemp,writeFile} from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import {fileURLToPath} from "node:url";
import * as documents from "../.opencode/tools/term_document.ts";
import * as results from "../.opencode/tools/term_result.ts";
import * as learning from "../.opencode/tools/term_learning.ts";
import * as trials from "../.opencode/tools/term_trial.ts";
import * as experiments from "../.opencode/tools/term_learning_trial.ts";
import { closeSyntheticAudit } from "./audit_fixture.mjs";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const directory=await mkdtemp(path.join(os.tmpdir(),"term-agent-tools-"));
process.env.TERM_EXTRACT_MEMORY_DIR=path.join(directory,"memory");
const context={directory:root,sessionID:"ses_protocol_parent",messageID:"msg_parent",agent:"term-extractor"};
const child={...context,sessionID:"ses_protocol_child",messageID:"msg_child",agent:"term-trial"};
const invoke=async(tool,args,ctx=context)=>JSON.parse(await tool.execute(args,ctx));
const save=async(file,value)=>writeFile(file,JSON.stringify(value),"utf8");
const execute=promisify(execFile);
const python=async(code)=>JSON.parse((await execute(process.env.TERM_EXTRACT_PYTHON || "python",["-B","-X","utf8","-c",code],{cwd:root,windowsHide:true,env:process.env,encoding:"utf8"})).stdout);
const clause=q=>[{id:0,条款标题:"Access Point",条款分类:"normal",相关条款:[],产品分类:"WLAN AP",定位标识:["<C1>","<C3>"],产品数量:q}];
const evidence={clauses:[{id:0,quantity_source_tags:["<C3>"],related_source_tags:[],notes:"数量明示于采购清单。"}],unresolved:[]};
const reflection={insights:[],no_experience_reason:"合成工具协议测试不凑经验。"};
const cases=[];
for(let i=0;i<3;i++){
  const source=path.join(directory,`source-${i}.json`),gold=path.join(directory,`gold-${i}.json`);
  await save(source,[{text:`<C1>Access Point ${i}<C2>Support Wi-Fi 6.<C3>Procurement quantity: ${i+2} units.`}]);
  await save(gold,clause(`${i+2} units`));
  cases.push({source,gold,...await invoke(learning.import_case,{input_path:source,labels_path:gold,family_id:`family-${i}`,split:i===0?"development":"regression"})});
}
const prepared=await invoke(documents.prepare,{input_path:cases[0].source,out_dir:path.join(directory,"extract")});
const study=await invoke(learning.begin,{input_path:cases[0].source,labels_path:cases[0].gold,family_id:"family-0",index_path:prepared.index_path});
assert.equal(study.state,"awaiting_blind_extraction");
const early=await invoke(learning.compare,{study_id:study.study_id,run_id:"run_not_submitted"});
assert.ok(early.error);
const status=await invoke(learning.status,{study_id:study.study_id});
assert.equal(status.labels_json,undefined);assert.equal(status.labels_path,undefined);
await invoke(documents.read,{index_path:prepared.index_path});
await invoke(results.checkpoint,{index_path:prepared.index_path,candidates_json:JSON.stringify([{条款标题:"Access Point",疑点:[]}])});
const draft=await invoke(results.validate,{index_path:prepared.index_path,result_json:JSON.stringify(clause("2 units")),evidence_json:JSON.stringify(evidence)});
await closeSyntheticAudit({index_path:prepared.index_path,result_path:draft.result_path,evidence_path:draft.evidence_path},context);
const committed=await invoke(results.commit,{index_path:prepared.index_path,result_path:draft.result_path,evidence_path:draft.evidence_path,reflection_json:JSON.stringify(reflection),model_id:"synthetic-protocol"});
assert.equal(committed.committed,true);
const compared=await invoke(learning.compare,{study_id:study.study_id,run_id:committed.learning.run_id});
assert.equal(compared.error,undefined,JSON.stringify(compared));
const reflected=await invoke(learning.reflect,{study_id:study.study_id,reflection_json:JSON.stringify(reflection)});
assert.equal(reflected.state,"reflected");
const candidate=await python("import sys,json;sys.path.insert(0,'.opencode/skills/term-extract/scripts');import evolution_store as e; print(json.dumps(e.propose_candidate('.',"+JSON.stringify({title:"合成协议候选",issue_type:"quantity",triggers:["quantity"],applies_when:"有明确设备采购数量时。",rule:"依据采购清单取设备数量并保留来源标签。",exclusions:"容量和接口数量不作为采购量。",correction_ids:[],source_ids:[cases[0].case_id]})+"),ensure_ascii=False))");
const plan=await invoke(experiments.prepare,{memory_id:candidate.memory_id,revision:candidate.revision,cases_json:JSON.stringify(cases.map((c,i)=>({case_id:c.case_id,role:["development","regression","counterexample"][i],...(i===2?{scope_note:"合成测试中的独立排除边界"}:{})})))});
assert.equal(plan.trials.length,6,JSON.stringify(plan));
const trial_id=plan.trials[0].trial_id;
await assert.rejects(trials.open.execute({trial_id},context),/term-trial/);
const ticket=await invoke(trials.open,{trial_id},child);
assert.ok(ticket.memory_pack);assert.equal(ticket.labels_json,undefined);
await invoke(trials.read,{trial_id},child);
await invoke(trials.checkpoint,{trial_id,candidates_json:JSON.stringify([{条款标题:"Access Point"}])},child);
await invoke(trials.validate,{trial_id,result_json:JSON.stringify(clause("2 units")),evidence_json:JSON.stringify(evidence)},child);
const frozen=await invoke(trials.commit,{trial_id},child);
assert.equal(frozen.committed,true,JSON.stringify(frozen));
assert.equal(frozen.learning.status,"trial_skipped");
const premature=await invoke(experiments.inspect,{experiment_id:plan.experiment_id});
assert.ok(premature.error,"未完成全部独立票不能揭示验证标签");
const counts=await python("import sys,json;sys.path.insert(0,'.opencode/skills/term-extract/scripts');import memory_store as s;from pathlib import Path\nwith s._db(Path('.')) as c: print(json.dumps({'sources':c.execute('SELECT COUNT(*) FROM learning_sources').fetchone()[0],'active':c.execute('SELECT COUNT(*) FROM active').fetchone()[0]}))");
assert.equal(counts.sources,1,"试验不作为学习来源");assert.equal(counts.active,0);
console.log(JSON.stringify({ok:true,atomic_agent_learning:true,labels_after_commit:true,scoped_trial:true,no_trial_learning_source:true,no_python_model_workflow:true,output_directory:directory,semantic_accuracy_tested:false}));
